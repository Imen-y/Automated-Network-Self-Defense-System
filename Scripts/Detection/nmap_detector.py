from datetime import datetime, timedelta, timezone
import re
import time

from scapy.all import IP, TCP, sniff

from Scripts.Telegram.telegram_notifier import send_notification
from Scripts.Cisco.cisco_acl_manager import block_ip
from Scripts.Logging.ansds_logger import log_event


# ---------------------------------
# Configuration
# ---------------------------------

NMAP_PORT_THRESHOLD = 10
TIME_WINDOW = 2
CORRELATION_WINDOW = 30
INTERFACE = "ens33"
AUTH_LOG = "/var/log/auth.log"


# ---------------------------------
# Tracking
# ---------------------------------

scan_attempts = {}
last_detection = {}

# Nmap detections waiting for SSH correlation
pending_nmap = {}


# ---------------------------------
# Nmap scan identification
# ---------------------------------

def identify_scan_type(tcp):
    """
    Identify the TCP scan type from packet flags.
    """

    flags = int(tcp.flags)

    SYN = 0x02
    FIN = 0x01
    PSH = 0x08
    URG = 0x20

    if flags == SYN:
        return "NMAP_SYN_SCAN"

    if flags == FIN:
        return "NMAP_FIN_SCAN"

    if flags == 0:
        return "NMAP_NULL_SCAN"

    if flags == (FIN | PSH | URG):
        return "NMAP_XMAS_SCAN"

    return None


# ---------------------------------
# SSH log parsing
# ---------------------------------

def get_recent_ssh_failures(source_ip, since_time):
    """
    Search /var/log/auth.log for Failed password
    events generated by the specified source IP.

    Only events occurring after since_time and inside
    the correlation window are considered.
    """

    failures = []

    try:
        with open(AUTH_LOG, "r", encoding="utf-8", errors="ignore") as log_file:
            lines = log_file.readlines()[-200:]

    except OSError as error:
        print(f"[-] Unable to read {AUTH_LOG}: {error}")
        return failures

    now = datetime.now(timezone.utc)

    for line in lines:

        if "Failed password" not in line:
            continue

        if f"from {source_ip}" not in line:
            continue

        # Expected format:
        # 2026-08-17T15:01:58.545990+00:00
        match = re.match(
            r"^(\d{4}-\d{2}-\d{2}T[0-9:.+\-]+)",
            line
        )

        if not match:
            continue

        timestamp_text = match.group(1)

        try:
            event_time = datetime.fromisoformat(timestamp_text)

            if event_time.tzinfo is None:
                event_time = event_time.replace(tzinfo=timezone.utc)

            event_time = event_time.astimezone(timezone.utc)

        except ValueError:
            continue

        if event_time < since_time:
            continue

        if now - event_time > timedelta(seconds=CORRELATION_WINDOW):
            continue

        failures.append(event_time)

    return failures


# ---------------------------------
# Correlation
# ---------------------------------

def check_ssh_correlation(source_ip):
    """
    Check whether SSH authentication failures from the same
    source IP occurred after the Nmap detection.
    """

    if source_ip not in pending_nmap:
        return False

    nmap_event = pending_nmap[source_ip]

    failures = get_recent_ssh_failures(
        source_ip,
        nmap_event["timestamp"]
    )

    if not failures:
        return False

    return True


# ---------------------------------
# Correlated response
# ---------------------------------

def trigger_correlated_response(source_ip):
    """
    Generate the final alert and block the source IP
    after Nmap + SSH correlation.
    """

    event = pending_nmap[source_ip]

    current_time = datetime.now(timezone.utc)

    alert_message = f"""
==================================================
              ANSDS SECURITY ALERT
==================================================

Attack Type       : Nmap + SSH Correlated

Date              : {current_time.strftime('%Y-%m-%d')}
Time              : {current_time.strftime('%H:%M:%S')}

Source IP         : {source_ip}
Destination IP    : {event['destination_ip']}

Scan Type         : {event['scan_type']}
Protocol          : TCP

Distinct Ports    : {event['distinct_ports']}
Nmap Window       : {TIME_WINDOW} seconds
Correlation Window: {CORRELATION_WINDOW} seconds

SSH Evidence      : Failed authentication detected
Correlation       : CONFIRMED

Status            : Nmap reconnaissance followed by SSH
                    authentication failures

==================================================
"""

    print("=" * 60)
    print("NMAP + SSH CORRELATION DETECTED!")
    print(f"Source IP         : {source_ip}")
    print(f"Destination IP    : {event['destination_ip']}")
    print(f"Scan Type         : {event['scan_type']}")
    print(f"Distinct Ports    : {event['distinct_ports']}")
    print(f"Correlation Window: {CORRELATION_WINDOW} seconds")
    print("SSH Evidence      : Failed authentication detected")

    log_event(
       "SSH_CORRELATION_CONFIRMED",
       source_ip=source_ip,
       destination_ip=event["destination_ip"],
       scan_type=event["scan_type"],
       distinct_ports=event["distinct_ports"],
       correlation_window=f"{CORRELATION_WINDOW}s"
   )

    print("=" * 60)

    if send_notification(alert_message):

        print("[+] Telegram notification sent successfully.")

        log_event(
           "TELEGRAM_ALERT_SENT",
           source_ip=source_ip,
           attack_type="Nmap + SSH Correlated"
        )

        if block_ip(source_ip):
            print(
                f"[+] IP {source_ip} blocked successfully on Cisco."
            )
        else:
            print(
                f"[-] Failed to block IP {source_ip} on Cisco."
            )

    else:
        print("[-] Failed to send Telegram notification.")

        log_event(
           "TELEGRAM_ALERT_FAILED",
           source_ip=source_ip,
           attack_type="Nmap + SSH Correlated"
        )

    # Remove the pending event after processing
    del pending_nmap[source_ip]


# ---------------------------------
# Packet callback
# ---------------------------------

def packet_callback(packet):
    """
    Process captured TCP packets and detect Nmap behavior.
    """

    if not (packet.haslayer(IP) and packet.haslayer(TCP)):
        return

    ip_src = packet[IP].src
    ip_dst = packet[IP].dst
    tcp = packet[TCP]

    scan_type = identify_scan_type(tcp)

    if scan_type is None:
        return

    current_time = datetime.now(timezone.utc)

    # ---------------------------------
    # Create source IP entry
    # ---------------------------------

    if ip_src not in scan_attempts:
        scan_attempts[ip_src] = {}

    # ---------------------------------
    # Create scan type entry
    # ---------------------------------

    if scan_type not in scan_attempts[ip_src]:
        scan_attempts[ip_src][scan_type] = []

    # ---------------------------------
    # Store port and timestamp
    # ---------------------------------

    scan_attempts[ip_src][scan_type].append(
        (tcp.dport, current_time)
    )

    # ---------------------------------
    # Keep only packets inside window
    # ---------------------------------

    scan_attempts[ip_src][scan_type] = [
        (port, timestamp)
        for port, timestamp in scan_attempts[ip_src][scan_type]
        if current_time - timestamp <= timedelta(
            seconds=TIME_WINDOW
        )
    ]

    # ---------------------------------
    # Count distinct destination ports
    # ---------------------------------

    unique_ports = {
        port
        for port, timestamp in scan_attempts[ip_src][scan_type]
    }

    count = len(unique_ports)

    print(
        f"[{scan_type}] {ip_src} -> {ip_dst} | "
        f"Distinct ports (last {TIME_WINDOW}s): {count}"
    )

    # ---------------------------------
    # Nmap detection
    # ---------------------------------

    detection_key = (ip_src, scan_type)

    if count >= NMAP_PORT_THRESHOLD:

        last_detection_time = last_detection.get(
            detection_key
        )

        if (
            last_detection_time is None
            or current_time - last_detection_time
            > timedelta(seconds=TIME_WINDOW)
        ):

            print("=" * 60)
            print("Nmap scan detected!")
            print(f"Scan Type      : {scan_type}")
            print(f"Source IP      : {ip_src}")
            print(f"Destination IP : {ip_dst}")
            print(f"Distinct Ports : {count}")
            print(f"Time Window    : {TIME_WINDOW} seconds")
            print("=" * 60)

            # Record the detection
            last_detection[detection_key] = current_time

            log_event(
               "NMAP_DETECTED",
               source_ip=ip_src,
               destination_ip=ip_dst,
               scan_type=scan_type,
               distinct_ports=count,
               time_window=f"{TIME_WINDOW}s"
            )

            # Store pending Nmap event
            pending_nmap[ip_src] = {
                "timestamp": current_time,
                "scan_type": scan_type,
                "destination_ip": ip_dst,
                "distinct_ports": count
            }

    # ---------------------------------
    # Check SSH correlation
    # ---------------------------------

    if ip_src in pending_nmap:

        if check_ssh_correlation(ip_src):

            trigger_correlated_response(ip_src)


# ---------------------------------
# Start packet capture
# ---------------------------------

def main():
    print("[*] Starting Nmap scan detection...")

    sniff(
        iface=INTERFACE,
        filter="tcp",
        prn=packet_callback,
        store=False
    )


if __name__ == "__main__":
    main()